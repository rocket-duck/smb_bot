import re

def _build_code_pattern(code: str) -> str:
    """
    Build a regex pattern for the given error code,
    allowing both Latin 'B'/'b'/'В'/'в' and 'C'/'c'/'С'/'с'.
    """
    parts = []
    for ch in code:
        if ch in ("B", "В", "b", "в"):
            parts.append("[BbВв]")
        elif ch in ("C", "С", "c", "с"):
            parts.append("[CcСс]")
        elif ch in ("A", "А", "a", "а"):
            parts.append("[AaАа]")
        elif ch in ("V", "v"):
            parts.append("[Vv]")
        else:
            parts.append(re.escape(ch))
    return "".join(parts)

